import { useEffect, useId, useState } from 'react';
import { L, onThemeChange, effectiveTheme } from '../i18n.js';

// Draws a Mermaid diagram (flowchart, architecture, sequence, timeline…).
// Mermaid is only loaded when needed and works offline.
let loading = null;
const dark = () => effectiveTheme() === 'dark' && !document.documentElement.classList.contains('print-mode');

function loadMermaid() {
  loading ??= import('mermaid').then(({ default: mermaid }) => mermaid);
  return loading.then((mermaid) => {
    // Configured on every render to follow the active theme.
    mermaid.initialize({
      startOnLoad: false,
      securityLevel: 'strict',
      theme: dark() ? 'dark' : 'neutral',
      fontFamily: 'system-ui, "Segoe UI", Roboto, sans-serif',
      flowchart: { htmlLabels: true, curve: 'basis' },
    });
    return mermaid;
  });
}

export default function Diagram({ code }) {
  const id = `diagram-${useId().replace(/[^a-zA-Z0-9]/g, '')}`;
  const [svg, setSvg] = useState(null);
  const [error, setError] = useState(null);
  const [theme, setTheme] = useState(effectiveTheme);
  useEffect(() => onThemeChange(() => setTheme(effectiveTheme())), []);

  useEffect(() => {
    let alive = true;
    loadMermaid()
      .then((mermaid) => mermaid.render(id, code))
      .then(({ svg: s }) => { if (alive) { setSvg(s); setError(null); } })
      .catch((e) => {
        document.getElementById(`d${id}`)?.remove(); // Mermaid leaves an orphan node when it fails
        if (alive) setError(e?.message ?? String(e));
      });
    return () => { alive = false; };
  }, [code, id, theme]);

  if (error) {
    return (
      <div className="diagram-error">
        <p><strong>{L('The diagram could not be drawn.', 'No se pudo dibujar el diagrama.')}</strong> {L('Ask your twin to fix it.', 'Pídele al gemelo que lo corrija.')}</p>
        <pre>{code}</pre>
      </div>
    );
  }
  if (!svg) return <div className="diagram muted">{L('Drawing diagram…', 'Dibujando diagrama…')}</div>;
  // The SVG is generated by Mermaid in strict mode (no scripts or arbitrary HTML).
  return <div className="diagram" dangerouslySetInnerHTML={{ __html: svg }} />;
}
